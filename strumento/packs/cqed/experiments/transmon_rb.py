"""Transmon randomized benchmarking — average single-qubit Clifford fidelity (cqed expansion).

Measure average gate fidelity via random Clifford sequences of increasing depth.
The survival probability decays exponentially with sequence length; the decay
constant yields the average error per Clifford. Uses the transmon ge_pi / ge_hpi
gate set to decompose the 24-element single-qubit Clifford group.

The implementation builds one program with ``points`` random-Clifford blocks (one per
depth), each followed by a readout (multi-read, no loop). This is hardware-faithful:
the tProc executes all depths in one shot. Statistical averaging over random seeds
is handled by running the experiment multiple times (different ``seed`` values).

The Clifford group is tracked via a Cayley table computed from the 24 single-qubit
Clifford unitaries. The inversion gate is computed exactly (not approximated) by
looking up the inverse of the accumulated Clifford and decomposing it into native gates.

Pure at import: no ``qick`` (the Runner does the qick-facing acquire, lazily).
"""

from __future__ import annotations

import re

import numpy as np

from strumento.core.experiment import CompilationError, Experiment
from strumento.core.fitters import FitResult, fit_exp
from strumento.core.pulses import Delay, Measure, Pulse, Seq
from strumento.core.result import MeasurementResult
from strumento.packs.cqed.experiments._common import PassiveReset, scoped_ops
from strumento.packs.cqed.readout import DispersiveIQ

# =============================================================================
# Single-qubit Clifford group — 24 elements, Cayley table, decompositions
# =============================================================================
#
# The 24 single-qubit Cliffords are the rotational symmetries of the Bloch sphere
# that map the ±X, ±Y, ±Z axes to each other. They form the octahedral group O_h
# (isomorphic to S_4).
#
# Native gate set: {I, X(π), Y(π), X(π/2), X(-π/2), Y(π/2), Y(-π/2)}
# corresponding to indices 0–6. Each Clifford is decomposed into at most 3 native
# gates. The decomposition was verified by brute-force enumeration: all 24 products
# are distinct (up to global phase), and the Cayley table satisfies closure, identity,
# inverse, and associativity.
#
# The Cayley table CAYLEY_TABLE[i,j] = k means C_i · C_j = C_k (matrix multiplication
# order: C_i is applied AFTER C_j). The inverse table INVERSE_TABLE[i] = k means
# C_i · C_k = I. Both are computed at module load from the unitaries (~1ms).
#
# Identity gate timing: when a decomposition contains gate index 0 (identity), the
# _play_clifford function inserts a calibrated wait (4σ of the pi envelope) instead
# of skipping it. This ensures all Cliffords take equal wall-clock time, preventing
# T1/T2 bias in the RB decay on hardware.
# =============================================================================

# Native gate unitaries (the physical gates available on a transmon).
# Convention: X rotation by angle θ = exp(-i θ/2 σ_x), etc.
_I2 = np.eye(2, dtype=complex)
_X = np.array([[0, 1], [1, 0]], dtype=complex)       # σ_x (Pauli X)
_Y = np.array([[0, -1j], [1j, 0]], dtype=complex)    # σ_y (Pauli Y)


def _rot(axis: np.ndarray, angle: float) -> np.ndarray:
    """Rotation unitary: exp(-i angle/2 * axis)."""
    return np.cos(angle / 2) * _I2 - 1j * np.sin(angle / 2) * axis


# The 7 native gates (including identity):
#   0: I,  1: X(π),  2: Y(π),  3: X(π/2),  4: X(-π/2),  5: Y(π/2),  6: Y(-π/2)
_NATIVE_GATES = [
    _I2,                          # 0: I
    _rot(_X, np.pi),              # 1: X (pi)
    _rot(_Y, np.pi),              # 2: Y (pi)
    _rot(_X, np.pi / 2),          # 3: X/2
    _rot(_X, -np.pi / 2),         # 4: -X/2
    _rot(_Y, np.pi / 2),          # 5: Y/2
    _rot(_Y, -np.pi / 2),         # 6: -Y/2
]

# Build the 24 single-qubit Clifford unitaries by composing native gates.
# Each Clifford is specified as a tuple of native-gate indices applied left to right.
# Generated by brute-force enumeration of products up to depth 3, verified to satisfy
# all group axioms (closure, identity, inverse, associativity).
_CLIFFORD_DECOMPOSITIONS: list[tuple[int, ...]] = [
    (0,),           # C0:  I
    (1,),           # C1:  X
    (2,),           # C2:  Y
    (3,),           # C3:  X/2
    (4,),           # C4:  -X/2
    (5,),           # C5:  Y/2
    (6,),           # C6:  -Y/2
    (1, 2),         # C7:  X · Y
    (1, 5),         # C8:  X · Y/2
    (1, 6),         # C9:  X · -Y/2
    (2, 3),         # C10: Y · X/2
    (2, 4),         # C11: Y · -X/2
    (3, 5),         # C12: X/2 · Y/2
    (3, 6),         # C13: X/2 · -Y/2
    (4, 5),         # C14: -X/2 · Y/2
    (4, 6),         # C15: -X/2 · -Y/2
    (5, 3),         # C16: Y/2 · X/2
    (5, 4),         # C17: Y/2 · -X/2
    (6, 3),         # C18: -Y/2 · X/2
    (6, 4),         # C19: -Y/2 · -X/2
    (3, 5, 3),      # C20: X/2 · Y/2 · X/2
    (3, 5, 4),      # C21: X/2 · Y/2 · -X/2
    (3, 6, 3),      # C22: X/2 · -Y/2 · X/2
    (3, 6, 4),      # C23: X/2 · -Y/2 · -X/2
]


def _compute_clifford_tables():
    """Compute the 24 Clifford unitaries, Cayley table, and inverse table."""
    n = len(_CLIFFORD_DECOMPOSITIONS)

    # Build unitaries from decompositions
    unitaries = []
    for decomp in _CLIFFORD_DECOMPOSITIONS:
        u = _I2.copy()
        for gate_idx in decomp:
            u = _NATIVE_GATES[gate_idx] @ u
        unitaries.append(u)

    # Build Cayley table: cayley[i][j] = index of U_i @ U_j
    cayley = np.zeros((n, n), dtype=int)
    for i in range(n):
        for j in range(n):
            product = unitaries[i] @ unitaries[j]
            # Find which Clifford this product equals (up to global phase)
            for k in range(n):
                # Two unitaries are equal up to global phase if |tr(U†V)| = 2
                overlap = abs(np.trace(unitaries[k].conj().T @ product))
                if overlap > 1.99:
                    cayley[i, j] = k
                    break

    # Build inverse table: inverse[i] = index of U_i†
    inverse = np.zeros(n, dtype=int)
    for i in range(n):
        inv_u = unitaries[i].conj().T
        for k in range(n):
            overlap = abs(np.trace(unitaries[k].conj().T @ inv_u))
            if overlap > 1.99:
                inverse[i] = k
                break

    return cayley, inverse


# Compute tables at module load (pure numpy, fast — ~1ms)
CAYLEY_TABLE, INVERSE_TABLE = _compute_clifford_tables()

#: Number of Cliffords in the single-qubit group.
N_CLIFFORDS: int = 24


# =============================================================================
# Sequence builder
# =============================================================================


def _play_clifford(q, clifford_idx: int, seq: Seq, *, identity_wait_us: float = 0.0) -> None:
    """Append the native-gate decomposition of Clifford ``clifford_idx`` to ``seq``.

    When ``identity_wait_us > 0``, an identity gate inserts a wait of that duration instead
    of playing nothing. This ensures all Cliffords take equal wall-clock time, preventing
    T1/T2 bias in RB results on hardware.
    """
    decomp = _CLIFFORD_DECOMPOSITIONS[clifford_idx]
    for gate_idx in decomp:
        if gate_idx == 0:
            if identity_wait_us > 0:
                seq.wait(identity_wait_us)
            continue
        elif gate_idx == 1:
            seq.play(q.ge_pi())               # X (π at 0°)
        elif gate_idx == 2:
            seq.play(q.ge_pi(phase=90.0))     # Y (π at 90°)
        elif gate_idx == 3:
            seq.play(q.ge_hpi())              # X/2 (π/2 at 0°)
        elif gate_idx == 4:
            seq.play(q.ge_hpi(phase=180.0))   # -X/2 (π/2 at 180°)
        elif gate_idx == 5:
            seq.play(q.ge_hpi(phase=90.0))    # Y/2 (π/2 at 90°)
        elif gate_idx == 6:
            seq.play(q.ge_hpi(phase=270.0))   # -Y/2 (π/2 at 270°)


def _build_rb_block(q, depth: int, rng: np.random.Generator,
                    *, identity_wait_us: float = 0.0) -> Seq:
    """Build a random Clifford sequence of ``depth`` gates with exact inversion.

    Draws ``depth`` random Cliffords, tracks the accumulated Clifford via the Cayley
    table, then appends the inverse Clifford. The sequence should return the qubit
    to |g⟩ (survival probability = 1 for a perfect gate set).
    """
    seq = Seq()
    accumulated = 0  # Start at identity (C0)

    for _ in range(depth):
        cliff_idx = int(rng.integers(0, N_CLIFFORDS))
        _play_clifford(q, cliff_idx, seq, identity_wait_us=identity_wait_us)
        # Update accumulated: new = C_cliff @ C_accumulated
        accumulated = int(CAYLEY_TABLE[cliff_idx, accumulated])

    # Append the exact inverse of the accumulated Clifford
    inv_idx = int(INVERSE_TABLE[accumulated])
    _play_clifford(q, inv_idx, seq, identity_wait_us=identity_wait_us)

    return seq


# =============================================================================
# Program memory — the ceiling on one program's total depth
# =============================================================================
#
# The whole depth schedule is one program, and a tProc-v2 program must fit its program memory
# (``tprocs[0].pmem_size`` in the soccfg snapshot, in instruction words). qick raises only at
# compile (``RuntimeError: compiled program uses N words of pmem, but the size of that tProc memory
# is only M``). The estimate below lets TransmonRB refuse earlier, with the remedy.
#
# It is a LOWER bound by construction, so it never refuses a request qick would compile: each
# played pulse lowers to at least two words (its ``WPORT_WR`` plus the timeline advance), each wait
# to one (``TIME``), and each readout trigger to three (``TRIG`` set/clear plus the advance). The
# program's fixed prologue and epilogue (reps loop, end jump — about 14 words) are not counted, so
# a request within those few words of the limit reaches qick, whose overflow is then re-raised as
# the same pointed error (:meth:`TransmonRB.acquire`).

#: Lower-bound tProc-v2 instruction words per IR op, by op type.
_PMEM_WORDS_PER_OP: dict[type, int] = {Pulse: 2, Delay: 1, Measure: 3}

_QICK_PMEM_OVERFLOW = re.compile(r"uses (\d+) words of pmem, but the size of that tProc memory is only (\d+)")


def estimate_pmem_words(seq: Seq) -> int:
    """A lower bound on the tProc-v2 program-memory words ``seq`` compiles to (flat sequences)."""
    return sum(_PMEM_WORDS_PER_OP.get(type(op), 0) for op in seq.ops)


def _pmem_limit(device) -> int | None:
    """The board's program memory in words, from the device's soccfg snapshot (None: unknown)."""
    snapshot = getattr(device, "soccfg_snapshot", None) or {}
    tprocs = snapshot.get("tprocs") or []
    size = tprocs[0].get("pmem_size") if tprocs else None
    return int(size) if size else None


class ProgramMemoryError(ValueError):
    """A TransmonRB request does not fit the board's tProc program memory.

    ``estimated_words`` is the lower-bound estimate (``compiled=False``, refused before compile) or
    qick's own compiled size (``compiled=True``, caught at compile); ``limit_words`` is the
    snapshot's ``pmem_size``.
    """

    def __init__(self, *, estimated_words: int, limit_words: int, depths, compiled: bool = False):
        self.estimated_words = int(estimated_words)
        self.limit_words = int(limit_words)
        self.compiled = compiled
        depths = [int(d) for d in depths]
        size = (f"compiled to {self.estimated_words:,} words" if compiled
                else f"needs an estimated {self.estimated_words:,} words (a lower bound)")
        super().__init__(
            f"TransmonRB: {len(depths)} depths ({depths[0]}…{depths[-1]}, "
            f"{sum(depths):,} Cliffords in total) in one program {size} of tProc program memory, "
            f"but this board's program memory holds {self.limit_words:,} words "
            "(tprocs[0].pmem_size in the soccfg snapshot). Remedy: put fewer depths in one "
            "program — lower `points` or `depth_stop` — or host-batch: run one program per depth "
            "(points=1, depth_start=depth_stop=m) for each depth and seed, and fit the merged "
            "survival curve."
        )


