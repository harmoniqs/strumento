def _played_duration_us(pulse, device) -> float:
    """Wall-clock duration of a ge gate pulse as the DAC plays it (µs)."""
    from strumento.core.compiler import _GAUSS_LENGTH_SIGMAS
    from strumento.core.pulses import Arb, Gaussian

    env = pulse.envelope
    if isinstance(env, Arb):
        fs = device.qubit._dac_rate(device.calib.qubit.f_ge)
        if not fs:
            raise ValueError("an Arb gate needs the drive DAC rate (soccfg snapshot) to time identity")
        return len(env.idata) / fs
    if isinstance(env, Gaussian):
        return _GAUSS_LENGTH_SIGMAS * env.sigma_us
    raise TypeError(f"cannot time an identity Clifford against a {type(env).__name__} gate")


class TransmonRB(PassiveReset, Experiment):
    """Single-qubit Clifford randomized benchmarking for the transmon.

    Builds ``points`` random-Clifford blocks (one per depth) in a single program, with one
    readout per block (multi-read, no loop axis). The depths are linearly spaced from
    ``depth_start`` to ``depth_stop``. Each block draws random Cliffords, tracks the
    accumulated group element via a Cayley table, and appends the exact inverse gate.

    The analyzer fits the survival probability decay P_0(m) = A·exp(-m/τ) + B and derives
    the depolarizing parameter p, average gate fidelity F = 1 - (1-p)/2, and error per
    Clifford.

    Statistical averaging: run with different ``seed`` values and average the fitted
    parameters; each invocation uses one random sequence per depth.

    **Program-memory ceiling.** All depths share one program, which must fit the board's tProc
    program memory: ``tprocs[0].pmem_size`` words in the device's soccfg snapshot (4096 on the
    shipped snapshots; 16384 on some boards). A Clifford costs about 3.7 words (1.83 gate pulses
    of 2 words each, plus the identity's wait), each depth adds its recovery Clifford, a reset
    wait and a 5-word readout, and the program a fixed ~14. So the sum of all depths in one
    program is capped near 1,100 Cliffords at 4096 words and near 4,400 at 16384 — the defaults
    (1…100, 10 points: 505 Cliffords, ~2k words) fit either. A request over the ceiling is refused
    in :meth:`sequence`, before anything compiles, with a :class:`ProgramMemoryError` naming the
    estimate, the limit and the remedy (fewer depths per program, or one program per depth on
    the host). The estimate is a lower bound, so it never refuses a request that would compile;
    the few words it leaves uncounted are caught at compile and raised as the same error.
    """

    def __init__(self, device, *, depth_start: int = 1, depth_stop: int = 100,
                 points: int = 10, seed: int = 42,
                 readout: DispersiveIQ | None = None, reset_delay_us: float | None = None,
                 overrides: dict | None = None, runner=None):
        super().__init__(device, runner=runner)
        self.depth_start = depth_start
        self.depth_stop = depth_stop
        self.points = points
        self.seed = seed
        self.readout = readout if readout is not None else DispersiveIQ.from_calib(device.calib.readout)
        # Passive reset before every depth block (µs); defaults to the readout relax_delay. A
        # measurement is not a reset — without it depth k starts from depth k−1's post-measurement
        # state and the survival curve is dragged toward ½ (a fake fast decay).
        self.reset_delay_us = reset_delay_us
        # Pulse overrides for the gates every Clifford is built from, scoped to
        # THIS experiment (the device's own ops are untouched).
        self.overrides = dict(overrides) if overrides else {}
        # Pre-compute the depth schedule
        self._depths = np.linspace(depth_start, depth_stop, points, dtype=int)
        # Identity gate wait = the PLAYED duration of the π gate, so all Cliffords take equal wall
        # clock time (no T1/T2 bias). This was once 4·envelope.sigma_us, which is 0 for
        # an Arb (e.g. DRAG) — identity Cliffords became free once drag_alpha was set.
        self._identity_wait_us = _played_duration_us(self._ops().ge_pi(), device)

    def _ops(self):
        """The transmon ops the Cliffords play through (with this experiment's overrides)."""
        return scoped_ops(self.device, self.overrides)

    def axes(self) -> tuple:
        return ()

    def sequence(self) -> tuple[Seq, tuple]:
        seq, sweeps = self._sequence_unchecked()
        limit = _pmem_limit(self.device)
        if limit is not None:
            estimate = estimate_pmem_words(seq)
            if estimate > limit:
                raise ProgramMemoryError(estimated_words=estimate, limit_words=limit,
                                         depths=self._depths)
        return seq, sweeps

    def _sequence_unchecked(self) -> tuple[Seq, tuple]:
        """The RB program's sequence, without the program-memory check."""
        q = self._ops()
        rng = np.random.default_rng(self.seed)
        reset = self._reset_delay()
        seq = Seq()
        for depth in self._depths:
            seq.wait(reset)   # every depth block from |g>
            block = _build_rb_block(q, int(depth), rng,
                                    identity_wait_us=self._identity_wait_us)
            seq += block
            seq.play(self.device.readout.dispersive_measure())
        return seq, ()

    def acquire(self, soc, *, record=None, **run_kw) -> MeasurementResult:
        """The standard one-program acquire, with qick's pmem overflow made pointed.

        The pre-compile estimate is a lower bound; a request within the few words it leaves
        uncounted reaches qick, whose overflow is re-raised as :class:`ProgramMemoryError`.
        """
        try:
            return super().acquire(soc, record=record, **run_kw)
        except CompilationError as exc:
            match = _QICK_PMEM_OVERFLOW.search(exc.constraint)
            if match is None:
                raise
            raise ProgramMemoryError(estimated_words=int(match.group(1)),
                                     limit_words=int(match.group(2)),
                                     depths=self._depths, compiled=True) from exc

    def analyze(self, result: MeasurementResult) -> FitResult:
        # Each read gives the survival probability at that depth
        avgi = np.asarray(result.avgi, dtype=float).ravel()
        avgq = np.asarray(result.avgq, dtype=float).ravel()
        iq = np.stack([avgi, avgq], axis=-1)
        signal = self.readout.project(iq).ravel()

        xpts = self._depths.astype(float)
        # Truncate if shapes don't match (defensive)
        n = min(len(signal), len(xpts))

        # Fit the survival probability decay: P_0(m) = A·exp(-m/tau) + B
        fit = fit_exp(xpts[:n], signal[:n])

        # Derive RB quantities from the decay constant
        tau = fit.derived.get("T1", 1.0)
        p = float(np.exp(-1.0 / tau)) if tau > 0 else 0.0
        # Single-qubit (d=2): F = 1 - (1-p)(d-1)/d = 1 - (1-p)/2
        fidelity = 1.0 - (1.0 - p) / 2.0
        error_per_clifford = (1.0 - p) / 2.0

        fit.derived["p"] = p
        fit.derived["fidelity"] = fidelity
        fit.derived["error_per_clifford"] = error_per_clifford
        return fit
